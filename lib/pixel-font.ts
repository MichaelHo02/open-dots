const FALLBACK = glyph("01110", "10001", "10001", "10001", "10001", "10001", "01110");

export function textScale(size: TextSize): number {
  switch (size) {
    case "s":
      return 1;
    case "m":
      return 2;
    case "l":
      return 3;
    default:
      return assertNever(size, "Unknown text size");
  }
}

function fontGlyphs(font: TextFont): Record<string, Glyph> {
  switch (font) {
    case "inter":
      return INTER;
    case "geist-mono":
      return MONO;
    default:
      return assertNever(font, "Unknown font");
  }
}

export function getGlyph(font: TextFont, char: string): Glyph {
  const glyphs = fontGlyphs(font);
  return glyphs[char] ?? glyphs[char.toUpperCase()] ?? FALLBACK;
}

export function glyphAdvance(scale: number): number {
  return GLYPH_W * scale + GLYPH_GAP * scale;
}

export function measureText(
  body: string,
  font: TextFont,
  size: TextSize,
): { width: number; height: number } {
  const scale = textScale(size);
  const chars = body.length || 1;
  const width =
    chars > 0
      ? chars * glyphAdvance(scale) - GLYPH_GAP * scale
      : GLYPH_W * scale;
  return {
    width,
    height: GLYPH_H * scale,
  };
}

export function textBounds(
  mark: Pick<TextMark, "x" | "y" | "body" | "font" | "size">,
): { x: number; y: number; width: number; height: number } {
  const { width, height } = measureText(mark.body, mark.font, mark.size);
  return {
    x: mark.x,
    y: mark.y,
    width,
    height,
  };
}

export function normalizeTextCoord(value: number, max: number): number {
  if (value >= 0 && value <= 1) {
    return Math.round(value * Math.max(0, max - 1));
  }
  return Math.max(0, Math.min(max - 1, Math.round(value)));
}

export function toPixelMark(
  mark: TextMark,
  size: Size,
): TextMark {
  return {
    ...mark,
    x: mark.x <= 1 ? Math.round(mark.x * size.width) : Math.round(mark.x),
    y: mark.y <= 1 ? Math.round(mark.y * size.height) : Math.round(mark.y),
  };
}

function stampGlyph(
  pixels: string[],
  size: Size,
  glyph: Glyph,
  x: number,
  y: number,
  scale: number,
  color: string,
) {
  for (let row = 0; row < GLYPH_H; row += 1) {
    const line = glyph[row] ?? "00000";
    for (let col = 0; col < GLYPH_W; col += 1) {
      if (line[col] !== "1") {
        continue;
      }
      for (let sy = 0; sy < scale; sy += 1) {
        for (let sx = 0; sx < scale; sx += 1) {
          const px = x + col * scale + sx;
          const py = y + row * scale + sy;
          if (inBounds(px, py, size)) {
            pixels[idx(px, py, size)] = color;
          }
        }
      }
    }
  }
}

export function rasterizeTextRun(
  pixels: string[],
  size: Size,
  mark: Pick<TextMark, "x" | "y" | "body" | "color" | "font" | "size">,
): string[] {
  if (!mark.body) {
    return pixels;
  }
  const next = clonePixels(pixels);
  const scale = textScale(mark.size);
  let cursorX = mark.x;
  for (const char of mark.body) {
    stampGlyph(next, size, getGlyph(mark.font, char), cursorX, mark.y, scale, mark.color);
    cursorX += glyphAdvance(scale);
  }
  return next;
}

export function eraseTextRun(
  pixels: string[],
  size: Size,
  mark: Pick<TextMark, "x" | "y" | "body" | "font" | "size">,
): string[] {
  if (!mark.body) {
    return pixels;
  }
  const box = textBounds(mark);
  const next = clonePixels(pixels);
  for (let py = box.y; py < box.y + box.height; py += 1) {
    for (let px = box.x; px < box.x + box.width; px += 1) {
      if (inBounds(px, py, size)) {
        next[idx(px, py, size)] = "";
      }
    }
  }
  return next;
}

export function syncTextRuns(
  pixels: string[],
  size: Size,
  previous: TextMark[],
  next: TextMark[],
): string[] {
  const prevById = new Map(previous.map((mark) => [mark.id, mark]));
  const nextById = new Map(next.map((mark) => [mark.id, mark]));
  let result = pixels;

  for (const mark of previous) {
    if (!nextById.has(mark.id)) {
      result = eraseTextRun(result, size, mark);
    }
  }

  for (const mark of next) {
    const prev = prevById.get(mark.id);
    if (
      prev &&
      prev.body === mark.body &&
      prev.x === mark.x &&
      prev.y === mark.y &&
      prev.color === mark.color &&
      prev.font === mark.font &&
      prev.size === mark.size
    ) {
      continue;
    }
    if (prev) {
      result = eraseTextRun(result, size, prev);
    }
    result = rasterizeTextRun(result, size, mark);
  }

  return result;
}
