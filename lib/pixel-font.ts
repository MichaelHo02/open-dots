/** Base glyph width in pixels (before size scale). */
export const GLYPH_W = 5;
/** Base glyph height in pixels (before size scale). */
export const GLYPH_H = 7;
/** Gap between glyphs in base pixels (before size scale). */
export const GLYPH_GAP = 1;

type Glyph = readonly string[];

function glyph(...rows: string[]): Glyph {
  return rows;
}

